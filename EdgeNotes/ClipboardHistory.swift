import AppKit
import SwiftUI
import Combine

/// 剪贴板历史：记录复制过的文字、图片、文件，挂在绳上的一张大卡片里，点一条就重新复制。
/// 密码管理器等标记为隐私/临时的内容不记录。
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let maxEntries = 40
    /// 剪贴板卡片在挂绳排布里的固定 id
    static let cardID = UUID(uuidString: "C11B0A2D-0000-4000-8000-000000000001")!
    /// 文字最多保存这么长，避免巨大文本拖慢界面
    static let maxTextLength = 20_000

    struct Entry: Identifiable, Codable, Equatable {
        enum Kind: String, Codable { case text, image, files }
        var id = UUID()
        var kind: Kind
        var text: String?
        /// 图片保存在 ClipboardHistory/ 目录下的文件名
        var imageFile: String?
        var files: [String]?
        var copiedAt = Date()
    }

    @Published private(set) var entries: [Entry] = []
    /// 刚点过的那条，卡片上短暂显示「已复制」
    @Published private(set) var justCopiedID: UUID?

    private var dataURL: URL?
    private(set) var imagesDir: URL?
    private var lastChangeCount = 0
    private var timer: Timer?
    private var saveWork: DispatchWorkItem?
    private var cancellables: Set<AnyCancellable> = []

    /// 这些类型表示「别记我」（nspasteboard.org 约定，1Password / 钥匙串等都会带上）
    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    func start(dataDirectory: URL) {
        dataURL = dataDirectory.appendingPathComponent("clipboard.json")
        let images = dataDirectory.appendingPathComponent("ClipboardHistory", isDirectory: true)
        try? FileManager.default.createDirectory(at: images, withIntermediateDirectories: true)
        imagesDir = images
        load()
        // 启动前就在剪贴板里的内容不算「新复制」
        lastChangeCount = NSPasteboard.general.changeCount

        AppSettings.shared.$clipboardHistoryEnabled
            .receive(on: RunLoop.main)
            .sink { [weak self] on in
                guard let self else { return }
                self.timer?.invalidate(); self.timer = nil
                guard on else { return }
                self.lastChangeCount = NSPasteboard.general.changeCount
                // 剪贴板没有变更通知，只能轮询 changeCount（开销很小）
                self.timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { _ in
                    Task { @MainActor in ClipboardHistory.shared.poll() }
                }
            }
            .store(in: &cancellables)
    }

    func imageURL(for entry: Entry) -> URL? {
        guard let name = entry.imageFile else { return nil }
        return imagesDir?.appendingPathComponent(name)
    }

    // MARK: - 采集

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        if let entry = Self.capture(pb, imagesDir: imagesDir) { insert(entry) }
    }

    /// 从剪贴板读出一条记录（图片会写进 imagesDir）；隐私内容返回 nil
    static func capture(_ pb: NSPasteboard, imagesDir: URL?) -> Entry? {
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: skipTypes) else { return nil }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return Entry(kind: .files, files: urls.map(\.path))
        }
        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return Entry(kind: .text, text: String(text.prefix(maxTextLength)))
        }
        if let imagesDir,
           let image = (pb.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage])?.first,
           let tiff = image.tiffRepresentation,
           let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            let name = "\(UUID().uuidString).png"
            guard (try? png.write(to: imagesDir.appendingPathComponent(name))) != nil else { return nil }
            return Entry(kind: .image, imageFile: name)
        }
        return nil
    }

    /// 新记录放最前；重复的文字/文件挪到最前而不是再存一份；超出上限的删掉（连同图片文件）
    func insert(_ entry: Entry) {
        var list = entries
        if let dup = list.firstIndex(where: { Self.sameContent($0, entry, imagesDir: imagesDir) }) {
            let old = list.remove(at: dup)
            if old.imageFile != entry.imageFile { deleteImage(of: entry) }
            var moved = old
            moved.copiedAt = entry.copiedAt
            list.insert(moved, at: 0)
        } else {
            list.insert(entry, at: 0)
        }
        while list.count > Self.maxEntries { deleteImage(of: list.removeLast()) }
        entries = list
        scheduleSave()
    }

    static func sameContent(_ a: Entry, _ b: Entry, imagesDir: URL?) -> Bool {
        guard a.kind == b.kind else { return false }
        switch a.kind {
        case .text: return a.text == b.text
        case .files: return a.files == b.files
        case .image:
            guard let dir = imagesDir, let fa = a.imageFile, let fb = b.imageFile else { return false }
            if fa == fb { return true }
            let da = try? Data(contentsOf: dir.appendingPathComponent(fa))
            let db = try? Data(contentsOf: dir.appendingPathComponent(fb))
            return da != nil && da == db
        }
    }

    // MARK: - 操作

    /// 把一条记录重新放回剪贴板
    func copy(_ entry: Entry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.kind {
        case .text:
            pb.setString(entry.text ?? "", forType: .string)
        case .files:
            let urls = (entry.files ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pb.writeObjects(urls)
        case .image:
            if let url = imageURL(for: entry), let image = NSImage(contentsOf: url) {
                pb.writeObjects([image])
            }
        }
        // 自己写进去的不再当成新复制，但把这条挪到最前
        lastChangeCount = pb.changeCount
        if let i = entries.firstIndex(of: entry), i > 0 {
            var list = entries
            var moved = list.remove(at: i)
            moved.copiedAt = Date()
            list.insert(moved, at: 0)
            entries = list
            scheduleSave()
        }
        justCopiedID = entry.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.justCopiedID == entry.id { self?.justCopiedID = nil }
        }
    }

    func remove(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
        deleteImage(of: entry)
        scheduleSave()
    }

    func clear() {
        entries.forEach(deleteImage(of:))
        entries = []
        scheduleSave()
    }

    private func deleteImage(of entry: Entry) {
        guard let url = imageURL(for: entry) else { return }
        try? FileManager.default.removeItem(at: url)
    }

    // MARK: - 存取

    private func load() {
        guard let dataURL, let data = try? Data(contentsOf: dataURL),
              let list = try? JSONDecoder().decode([Entry].self, from: data) else { return }
        entries = Array(list.prefix(Self.maxEntries))
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.flush() }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5, execute: work)
    }

    func flush() {
        saveWork?.cancel(); saveWork = nil
        guard let dataURL, let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: dataURL, options: .atomic)
    }
}

/// 挂绳上的剪贴板大卡片
struct ClipboardCard: View {
    @ObservedObject var history: ClipboardHistory
    let privacy: Bool
    @State private var hoveredRow: UUID?

    static let size = CGSize(width: 236, height: 206)

    var body: some View {
        ZStack(alignment: .top) {
            VStack(alignment: .leading, spacing: 0) {
                HStack(spacing: 5) {
                    Image(systemName: "doc.on.clipboard").font(.system(size: 10, weight: .semibold))
                    Text(L("剪贴板")).font(.system(size: 11.5, weight: .semibold))
                    Text("\(history.entries.count)").font(.system(size: 10)).foregroundStyle(.secondary)
                    Spacer()
                    if !history.entries.isEmpty {
                        Button { history.clear() } label: {
                            Image(systemName: "trash").font(.system(size: 10))
                        }
                        .buttonStyle(.plain)
                        .foregroundStyle(.secondary)
                        .help(L("清空剪贴板历史"))
                    }
                }
                .padding(.horizontal, 10)
                .padding(.top, 14)
                .padding(.bottom, 6)
                Divider().opacity(0.5)
                if history.entries.isEmpty {
                    Text(L("复制过的文字、图片、文件会出现在这里，点一下就能再次复制"))
                        .font(.system(size: 10))
                        .foregroundStyle(.secondary)
                        .multilineTextAlignment(.center)
                        .frame(maxWidth: .infinity, maxHeight: .infinity)
                        .padding(14)
                } else {
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(history.entries) { entry in row(entry) }
                        }
                        .padding(5)
                    }
                }
            }
            .frame(width: Self.size.width, height: Self.size.height)
            .background(RoundedRectangle(cornerRadius: 5).fill(Color(red: 0.97, green: 0.97, blue: 0.95)))
            .overlay(RoundedRectangle(cornerRadius: 5).strokeBorder(Color.black.opacity(0.07)))
            .foregroundStyle(Color.black.opacity(0.82))
            .padding(.top, 8)

            HStack(spacing: Self.size.width - 70) {
                Clothespin()
                Clothespin()
            }
            .offset(y: -4)
        }
        .shadow(color: .black.opacity(0.2), radius: 5, y: 3)
    }

    private func row(_ entry: ClipboardHistory.Entry) -> some View {
        let copied = history.justCopiedID == entry.id
        return HStack(spacing: 7) {
            content(entry)
            Spacer(minLength: 0)
            if copied {
                Image(systemName: "checkmark.circle.fill").foregroundStyle(.green).font(.system(size: 12))
            }
        }
        .padding(.horizontal, 6)
        .padding(.vertical, 5)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(
            RoundedRectangle(cornerRadius: 4)
                .fill(copied ? Color.green.opacity(0.15) : (hoveredRow == entry.id ? Color.accentColor.opacity(0.13) : Color.black.opacity(0.03)))
        )
        .contentShape(Rectangle())
        .onHover { inside in
            if inside { hoveredRow = entry.id } else if hoveredRow == entry.id { hoveredRow = nil }
        }
        .onTapGesture { history.copy(entry) }
        .help(L("点击复制"))
        .contextMenu {
            Button(L("复制")) { history.copy(entry) }
            Button(L("挂到绳上")) { ClotheslineController.shared.hang(entry) }
            Divider()
            Button(L("从历史中删除"), role: .destructive) { history.remove(entry) }
        }
    }

    @ViewBuilder
    private func content(_ entry: ClipboardHistory.Entry) -> some View {
        switch entry.kind {
        case .text:
            Text(entry.text?.trimmingCharacters(in: .whitespacesAndNewlines) ?? "")
                .font(.system(size: 10.5))
                .lineLimit(2)
                .blur(radius: privacy ? 4 : 0)
        case .image:
            HStack(spacing: 6) {
                if let url = history.imageURL(for: entry), let thumb = ClipboardThumbs.image(url) {
                    Image(nsImage: thumb).resizable().aspectRatio(contentMode: .fill)
                        .frame(width: 54, height: 36).clipShape(RoundedRectangle(cornerRadius: 3))
                        .blur(radius: privacy ? 5 : 0)
                }
                Text(L("图片")).font(.system(size: 10)).foregroundStyle(.secondary)
            }
        case .files:
            let files = entry.files ?? []
            HStack(spacing: 6) {
                if let first = files.first {
                    Image(nsImage: NSWorkspace.shared.icon(forFile: first)).resizable().frame(width: 22, height: 22)
                }
                Text(files.count > 1
                     ? LF("%@ 等 %@ 个文件", URL(fileURLWithPath: files[0]).lastPathComponent, files.count)
                     : URL(fileURLWithPath: files.first ?? "").lastPathComponent)
                    .font(.system(size: 10.5))
                    .lineLimit(1)
            }
        }
    }
}

/// 剪贴板图片缩略图缓存
@MainActor
enum ClipboardThumbs {
    private static let cache = NSCache<NSURL, NSImage>()

    static func image(_ url: URL) -> NSImage? {
        if let hit = cache.object(forKey: url as NSURL) { return hit }
        guard let image = NSImage(contentsOf: url) else { return nil }
        let thumb = NoteBodyRendering.scale(image, maxWidth: 120)
        cache.setObject(thumb, forKey: url as NSURL)
        return thumb
    }
}
